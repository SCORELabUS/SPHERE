import { promisify } from 'node:util';
import child_process from 'node:child_process';
import { mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process, { env } from 'node:process';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

import { format } from 'prettier';

const exec = promisify(child_process.exec);
const __filename = fileURLToPath(import.meta.url);

const CHANGELOG_DIR_DATA_PATH = 'src/modules/presentation/pages/changelog/data';
const ARGS_CONFIG = {
  sphere: {
    repository: 'Alex-GF/SPHERE',
    filename: 'sphere.ts',
    templateVariableName: 'SPHERE_CHANGELOG',
  },
  'pricing-int': {
    repository: 'isa-group/Pricing-Intelligence-Interpretation-Process',
    filename: 'piip.ts',
    templateVariableName: 'PIIP_CHANGELOG',
  },
};

const target = process.argv[2];
if (process.argv.length !== 3 || !target || !ARGS_CONFIG[target]) {
  printUsage();
  process.exit(1);
}

const isGitHubCliInstalled = await checkGithubCliInstalled();
if (!isGitHubCliInstalled) {
  console.error('Github CLI is not installed');
  process.exit(1);
}
await checkGithubToken();

env.GH_REPO = ARGS_CONFIG[process.argv[2]].repository;
env.GH_TELEMETRY = false;
env.GH_SPINNER_DISABLED = true;
env.GH_NO_UPDATE_NOTIFIER = true;
env.GH_NO_EXTENSION_UPDATE_NOTIFIER = true;

try {
  const tempDir = await mkdtemp(path.join(tmpdir(), 'genchangelog-'));
  const files = await downloadChangelogsFromRepo(tempDir);
  if (files.length === 0) {
    console.log(`${env.GH_REPO} repository does not have any releases or valid changelogs`);
    process.exit(0);
  }

  const changelog = await mergeChangelogs(tempDir, files);

  console.log(`Generating a typescript file in ${tempDir} directory...`);
  const code = await generateChangelog(
    changelog,
    ARGS_CONFIG[process.argv[2]].templateVariableName
  );

  const dstPath = path.join(
    process.cwd(),
    CHANGELOG_DIR_DATA_PATH,
    ARGS_CONFIG[process.argv[2]].filename
  );
  await updateChangelog(code, dstPath);
  console.log(`Cleaning ${tempDir} directory`);
  await rm(tempDir, { force: true, recursive: true });
} catch (err) {
  console.error(err);
  process.exit(1);
}

function printUsage() {
  console.error(`Usage: node ${path.basename(__filename)} <sphere|pricing-int>`);
}

async function checkGithubCliInstalled() {
  try {
    await exec('command -v gh');
    return true;
  } catch (error) {
    return false;
  }
}

async function checkGithubToken() {
  try {
    const { stdout, stderr } = await exec('gh auth status');
    console.log(stdout);
  } catch (error) {
    console.error(error.stderr);
    console.error(`Please set GH_TOKEN environment variable:
read -s -p 'Enter Github PAT: ' GH_TOKEN
export GH_TOKEN`);
    process.exit(1);
  }
}

async function downloadChangelogsFromRepo(directory) {
  const { stdout, stderr } = await exec(
    "gh api repos/{owner}/{repo}/releases --paginate --jq 'map(.tag_name)'"
  );

  const tags = JSON.parse(stdout);
  const files = [];

  if (tags.length === 0) {
    return files;
  }

  console.log(`Downloading changelogs from ${env.GH_REPO} repository in ${directory} directory`);
  for (const tag of tags) {
    try {
      await exec(`gh release download ${tag} --dir ${directory} --pattern 'changelog-*.json'`);
      const cleanTag = tag.startsWith('v') ? tag.slice(1) : tag;
      const filename = `${directory}/changelog-${cleanTag}.json`;
      files.push(filename);
    } catch (error) {
      continue;
    }
  }
  console.log(`Done downloading changelog assets.`);
  return files;
}

async function mergeChangelogs(directory, files) {
  const res = [];
  console.log(`Merging downloaded changelogs in ${directory} directory`);
  for (const file of files) {
    const changelog = await readFile(file, 'utf8');
    res.push(JSON.parse(changelog));
  }
  console.log(`Done merging`);

  return res;
}

async function generateChangelog(changelog, templateVariableName) {
  const today = new Date();
  let res = `// This file is autogenerated by ${path.basename(__filename)} script at ${today.toISOString()}\n`;
  res += "import type { Release } from '../types'\n\n";
  res += `export const ${templateVariableName}: Release[] = ${JSON.stringify(changelog)};`;
  return await format(res, { parser: 'typescript' });
}

async function updateChangelog(code, destination) {
  const src = Buffer.from(code);
  const destinationData = await readFile(destination, 'utf8');
  const dst = Buffer.from(destinationData);
  if (!src.equals(dst)) {
    console.log(`Updating file ${destination}. Written ${Buffer.byteLength(src)} bytes.`);
    await writeFile(destination, code);
  } else {
    console.log(`File ${destination} is already updated`);
  }
}
